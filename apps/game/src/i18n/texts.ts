export type Locale = 'es-UY' | 'en';
const CATALOGS: Record<Locale, Record<TextKey, string>> = { 'es-UY': esUY, en };

let locale: Locale = 'es-UY';
export const getLocale = (): Locale => locale;
export function setLocale(next: Locale): void {
  locale = next;
  document.documentElement.lang = next;
}
export const detectLocale = (): Locale => (navigator.language.toLowerCase().startsWith('es') ? 'es-UY' : 'en');

export function t(key: TextKey, params?: Record<string, string | number>): string {
  let out = CATALOGS[locale][key];
  if (params) for (const [k, v] of Object.entries(params)) out = out.replaceAll(`{${k}}`, String(v));
  return out;
}
